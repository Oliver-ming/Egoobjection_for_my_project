#!/usr/bin/env python3
"""Test-time augmentation (multi-scale + optional horizontal flip) for MMDetection configs.

For each (scale, flip) variant this script:
  1. writes a tiny config that overrides ``test_pipeline`` / ``test_dataloader``;
  2. runs ``mmdet/tools/dist_infer.sh`` (multi-GPU via ``--gpus``);
  3. if the variant was flipped, maps boxes back to the original frame
     (``x' = W - x - w``).  Co-DINO / DINO heads only undo ``scale_factor``;
     they do **not** un-flip, so this post-process is required;
  4. fuses all variants with ``tools/ensemble.py`` (WBF by default);
  5. when the annotation json has GT, prints a per-variant + fused AP table.

Example (1 GPU, flock-wrapped by the caller or via ``--flock``)::

    CUDA_VISIBLE_DEVICES=3 PORT=29931 python mmdet/tools/tta_infer.py \\
        --config mmdet/configs/codino_swinl_ego.py \\
        --checkpoint work_dirs/codino_smoke/train_s1333/epoch_1.pth \\
        --ann work_dirs/codino_smoke/val_sub200.json \\
        --out-dir work_dirs/codino_verify/tta \\
        --scales 1333x800 --flip --gpus 1 --flock logs/gpu3.lock
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Optional, Sequence

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.common import dump_json, load_json, load_predictions
from tools.ensemble import FusionConfig, METHODS, CONF_TYPES, ensemble_predictions

SOLUTION = Path(__file__).resolve().parents[2]
DIST_INFER = SOLUTION / "mmdet" / "tools" / "dist_infer.sh"
PY = SOLUTION / "env" / "bin" / "python"
SCALE_RE = re.compile(r"^(\d+)[xX](\d+)$")


def parse_scales(raw: str) -> list[tuple[int, int]]:
    """Parse ``1333x800,1600x960`` into ``[(1333, 800), ...]`` (long, short) as mmdet Resize expects."""
    scales = []
    for part in raw.replace(" ", "").split(","):
        if not part:
            continue
        m = SCALE_RE.match(part)
        if not m:
            raise argparse.ArgumentTypeError(
                f"bad scale {part!r}; expected WIDTHxHEIGHT like 1333x800")
        # mmdet Resize scale=(max_long, max_short) with keep_ratio=True uses
        # the convention (max_edge_for_long_side, max_edge_for_short_side) when
        # written as (1333, 800); we accept "1333x800" as (1333, 800).
        scales.append((int(m.group(1)), int(m.group(2))))
    if not scales:
        raise argparse.ArgumentTypeError("need at least one scale")
    return scales


def variant_name(scale: tuple[int, int], flip: bool) -> str:
    return f"{scale[0]}x{scale[1]}_{'flip' if flip else 'orig'}"


def write_variant_config(base_config: Path, out_cfg: Path, scale: tuple[int, int],
                         flip: bool) -> None:
    """Emit a one-file config that inherits ``base_config`` and overrides the test pipeline."""
    # PackDetInputs must expose flip meta when RandomFlip is present so DetTTA /
    # debugging can see it; our post-process uses the ann widths instead.
    meta = ("img_id", "img_path", "ori_shape", "img_shape", "scale_factor")
    if flip:
        meta = meta + ("flip", "flip_direction")
    steps = [
        "    dict(type='LoadImageFromFile', backend_args=None),",
        "    dict(type='Resize', scale=test_scale, keep_ratio=True),",
    ]
    if flip:
        steps.append("    dict(type='RandomFlip', prob=1.0),")
    steps.append(f"    dict(type='PackDetInputs', meta_keys={meta!r}),")
    pipeline_body = "\n".join(steps)
    content = (
        "# Auto-generated by tta_infer.py — do not edit.\n"
        f"_base_ = [{str(base_config.resolve())!r}]\n"
        f"\ntest_scale = {scale!r}\n"
        "test_pipeline = [\n"
        f"{pipeline_body}\n"
        "]\n"
        "test_dataloader = dict(dataset=dict(pipeline=test_pipeline))\n"
    )
    out_cfg.parent.mkdir(parents=True, exist_ok=True)
    out_cfg.write_text(content)


def unflip_xywh(preds: list[dict], image_sizes: dict[int, tuple[int, int]]) -> list[dict]:
    """Map horizontally-flipped COCO xywh boxes back to the original frame: x' = W - x - w."""
    out = []
    for p in preds:
        W, _H = image_sizes[p["image_id"]]
        x, y, w, h = p["bbox"]
        out.append({
            "image_id": p["image_id"],
            "category_id": p["category_id"],
            "bbox": [W - x - w, y, w, h],
            "score": p["score"],
        })
    return out


def run_dist_infer(config: Path, checkpoint: Path, ann: Path, out_prefix: Path,
                   gpus: int, port: int, flock_path: Optional[Path],
                   extra_args: Sequence[str]) -> None:
    cmd = [
        "bash", str(DIST_INFER),
        str(config), str(checkpoint), str(gpus),
        str(ann), str(out_prefix),
        *extra_args,
    ]
    env = os.environ.copy()
    env["PORT"] = str(port)
    if flock_path is not None:
        flock_path.parent.mkdir(parents=True, exist_ok=True)
        cmd = ["flock", str(flock_path), *cmd]
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, env=env, cwd=str(SOLUTION))


def evaluate_table(gt_path: Path, rows: list[tuple[str, Path]]) -> list[dict]:
    from tools.coco_eval import evaluate, load_gt
    coco_gt = load_gt(gt_path, verbose=False)
    table = []
    print("\nTTA AP table (COCO mAP@0.5:0.95):")
    print(f"{'variant':<28s} {'AP':>7s} {'AP50':>7s} {'AP75':>7s} {'n':>7s}")
    for name, path in rows:
        m = evaluate(coco_gt, path, verbose=False)
        table.append({"variant": name, "path": str(path),
                      "AP": m["AP"], "AP50": m["AP50"], "AP75": m["AP75"],
                      "num_predictions": m["num_predictions"]})
        print(f"{name:<28s} {m['AP']:7.4f} {m['AP50']:7.4f} {m['AP75']:7.4f} "
              f"{m['num_predictions']:7d}")
    return table


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", type=Path, required=True)
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--ann", type=Path, required=True, help="val/test/subset COCO json")
    p.add_argument("--out-dir", type=Path, required=True,
                   help="directory for per-variant + fused jsons")
    p.add_argument("--scales", type=parse_scales, default=parse_scales("1333x800"),
                   help="comma-separated WIDTHxHEIGHT, e.g. 1333x800,1600x960,1920x1152")
    p.add_argument("--flip", action="store_true",
                   help="also run a horizontal-flip view of every scale")
    p.add_argument("--gpus", type=int, default=1)
    p.add_argument("--port", type=int, default=29931,
                   help="torch.distributed master port (unique per concurrent job)")
    p.add_argument("--flock", type=Path, default=None,
                   help="optional lock file; each GPU variant is wrapped in flock")
    p.add_argument("--method", choices=METHODS, default="wbf")
    p.add_argument("--iou-thr", type=float, default=0.6)
    p.add_argument("--conf-type", choices=CONF_TYPES, default="max",
                   help="WBF fused-score rule (default max: avg under-scores "
                        "singleton clusters from correlated TTA views)")
    p.add_argument("--skip-box-thr", type=float, default=0.001)
    p.add_argument("--max-per-image", type=int, default=100)
    p.add_argument("--sigma", type=float, default=0.5, help="soft-NMS sigma")
    p.add_argument("--weights", type=float, nargs="+", default=None,
                   help="optional per-variant fusion weights (default: all 1)")
    p.add_argument("--skip-infer", action="store_true",
                   help="reuse existing <variant>.bbox.json files; only unflip/fuse/eval")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    out_dir = args.out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg_dir = out_dir / "_tta_cfgs"
    ann = args.ann.resolve()
    config = args.config.resolve()
    checkpoint = args.checkpoint.resolve()

    ann_data = load_json(ann)
    image_sizes = {im["id"]: (im["width"], im["height"]) for im in ann_data["images"]}
    has_gt = bool(ann_data.get("annotations"))

    flips = [False, True] if args.flip else [False]
    variants: list[tuple[str, tuple[int, int], bool, Path]] = []
    for scale in args.scales:
        for flip in flips:
            name = variant_name(scale, flip)
            variants.append((name, scale, flip, out_dir / name))

    raw_pred_lists: list[list[dict]] = []
    eval_rows: list[tuple[str, Path]] = []

    for i, (name, scale, flip, prefix) in enumerate(variants):
        raw_json = Path(str(prefix) + ".bbox.json")
        final_json = out_dir / f"{name}.json"  # post-processed (unflipped if needed)
        if not args.skip_infer:
            vcfg = cfg_dir / f"{name}.py"
            write_variant_config(config, vcfg, scale, flip)
            run_dist_infer(
                vcfg, checkpoint, ann, prefix, args.gpus,
                port=args.port + i, flock_path=args.flock, extra_args=())
        if not raw_json.is_file():
            raise FileNotFoundError(f"missing inference output {raw_json}")
        preds = load_predictions(raw_json)
        if flip:
            preds = unflip_xywh(preds, image_sizes)
        dump_json(preds, final_json)
        raw_pred_lists.append(preds)
        eval_rows.append((name, final_json))
        print(f"saved {final_json} ({len(preds)} boxes, flip={flip})")

    fusion_cfg = FusionConfig(
        method=args.method, iou_thr=args.iou_thr, skip_box_thr=args.skip_box_thr,
        conf_type=args.conf_type, max_per_image=args.max_per_image, sigma=args.sigma)
    fused = ensemble_predictions(raw_pred_lists, args.weights, fusion_cfg)
    fused_path = out_dir / "fused.json"
    dump_json(fused, fused_path)
    print(f"fused {sum(map(len, raw_pred_lists))} -> {len(fused)} boxes via {fusion_cfg.method} "
          f"-> {fused_path}")
    eval_rows.append(("fused", fused_path))

    table = None
    if has_gt:
        table = evaluate_table(ann, eval_rows)
        dump_json({"variants": table, "fusion": {
            "method": fusion_cfg.method, "iou_thr": fusion_cfg.iou_thr,
            "conf_type": fusion_cfg.conf_type, "scales": [list(s) for s in args.scales],
            "flip": args.flip,
        }}, out_dir / "tta_metrics.json", indent=2)


if __name__ == "__main__":
    main()
